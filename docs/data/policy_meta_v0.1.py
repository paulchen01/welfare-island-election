def load_names(game_js):
    """從遊戲程式取出政策名稱與類型，避免手抄錯誤。"""
    src = pathlib.Path(game_js).read_text(encoding='utf8')
    names = dict(re.findall(r"id:'([a-z0-9]+)'(?:,ev:'e\d')?,name:'([^']+)'", src))
    return names

