def stats(rows):
    c, s = collections.Counter(), collections.Counter()
    for p in rows:
        for v in p['views']:
            c[v['view']] += 1
            s[(v['view'], v['stance'])] += 1
    return c, s


def main():
    here = pathlib.Path(__file__).parent
    old = json.loads((here / 'policy_meta_v0.1.json').read_text(encoding='utf8'))
    ids = [p['id'] for p in old]
    missing, extra = set(ids) - set(VIEWS), set(VIEWS) - set(ids)
    assert not missing and not extra, (missing, extra)

    new, lines = [], []
    for p in old:
        q = dict(p)
        q['views'] = [{'view': V[a], 'stance': S[b], 'why': w} for a, b, w in VIEWS[p['id']]]
        assert any(v['stance'] != '支持' for v in q['views']) or p['id'] in ALL_SUPPORT_OK, p['id']
        new.append(q)
        fmt = lambda vs: '；'.join(f"{v['view']}（{v['stance']}）{v['why']}" for v in vs)
        if fmt(p['views']) != fmt(q['views']):
            lines.append(f"| {p['id']} | {p['name']} | {fmt(p['views'])} | {fmt(q['views'])} |")

    (here / 'policy_meta_v0.2.json').write_text(json.dumps(new, ensure_ascii=False, indent=1) + '\n', encoding='utf8')

    c1, s1 = stats(old)
    c2, s2 = stats(new)
    md = ['# 政策觀點資料 v0.1 → v0.2 對照', '',
          '由 `policy_meta_v0.2.py` 產生，請勿手動修改。', '',
          '## 七觀點分布', '',
          '| 觀點 | v0.1 次數 | v0.2 次數 | v0.2 支持／保留／批評 |', '|---|---|---|---|']
    for k in ORDER:
        md.append(f"| {k} | {c1[k]} | {c2[k]} | {s2[(k,'支持')]}／{s2[(k,'保留')]}／{s2[(k,'批評')]} |")
    md += ['', f'## 有變動的政策（{len(lines)} 張）', '',
           '| id | 政策 | v0.1 | v0.2 |', '|---|---|---|---|'] + lines + ['']
    (here / 'policy_meta_v0.2_changes.md').write_text('\n'.join(md), encoding='utf8')

    for k in ORDER:
        print(f"{k:6} {c1[k]:3} → {c2[k]:3}  支{s2[(k,'支持')]:3} 保{s2[(k,'保留')]:3} 批{s2[(k,'批評')]:3}")
    print('changed:', len(lines), 'of', len(old))


